import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';

import {
  GENERATED_FILES,
  GENERATED_HEADER,
  generateFromJsonText,
  packageRootFromModuleUrl,
} from './generate.js';

const packageRoot = join(dirname(fileURLToPath(import.meta.url)), '..');

function normalizeLf(text: string): string {
  return text.replaceAll('\r\n', '\n');
}

describe('generate', () => {
  const jsonText = readFileSync(join(packageRoot, 'src', 'tokens.json'), 'utf8');
  const files = generateFromJsonText(jsonText);

  it('emits every committed generated file without drift', () => {
    for (const name of GENERATED_FILES) {
      const committed = readFileSync(join(packageRoot, 'generated', name), 'utf8');
      expect(normalizeLf(files[name])).toBe(normalizeLf(committed));
    }
  });

  it('is deterministic', () => {
    expect(generateFromJsonText(jsonText)).toEqual(files);
  });

  it('stamps the generated header', () => {
    expect(files['tokens.ts'].startsWith(GENERATED_HEADER)).toBe(true);
    expect(files['tokens.swift'].startsWith(GENERATED_HEADER)).toBe(true);
    expect(files['Tokens.kt'].startsWith(GENERATED_HEADER)).toBe(true);
    expect(files['tokens.css']).toContain('Generated by @jot/tokens. Do not edit.');
  });

  it('resolves the package root from this module', () => {
    expect(packageRootFromModuleUrl(import.meta.url)).toBe(packageRoot);
  });

  it('embeds authored values in the TypeScript output', () => {
    expect(files['tokens.ts']).toContain('"SF Pro"');
    expect(files['tokens.ts']).toContain('fast: 120');
  });
});

function emitTsValue(value: unknown, indent: number, path: string): string {
  const pad = '  '.repeat(indent);
  const inner = '  '.repeat(indent + 1);
  if (value === null) {
    throw new Error(`null token at ${path}`);
  }
  switch (typeof value) {
    case 'string':
      return JSON.stringify(value);
    case 'number':
      if (!Number.isFinite(value)) {
        throw new Error(`non-finite number at ${path}`);
      }
      return Object.is(value, -0) ? '0' : String(value);
    case 'boolean':
      return value ? 'true' : 'false';
    case 'object':
      break;
    default:
      throw new Error(`unsupported token at ${path}: ${typeof value}`);
  }
  if (Array.isArray(value)) {
    const items = value.map((item, index) =>
      emitTsValue(item, indent + 1, `${path}[${String(index)}]`),
    );
    if (items.every((item) => !item.includes('\n'))) {
      return `[${items.join(', ')}]`;
    }
    return `[\n${items.map((item) => `${inner}${item}`).join(',\n')},\n${pad}]`;
  }
  const entries = Object.entries(value);
  if (entries.length === 0) {
    return '{}';
  }
  const lines = entries.map(([key, child]) => {
    const renderedKey = isIdent(key) ? key : JSON.stringify(key);
    return `${inner}${renderedKey}: ${emitTsValue(child, indent + 1, `${path}.${key}`)}`;
  });
  return `{\n${lines.join(',\n')},\n${pad}}`;
}

function isNumberArray(value: unknown): value is readonly number[] {
  return Array.isArray(value) && value.every((item) => typeof item === 'number');
}

function cssLeaf(
  path: readonly string[],
  value: string | number | boolean | readonly number[],
): string {
  if (typeof value === 'boolean') {
    return value ? '1' : '0';
  }
  if (typeof value === 'string') {
    if (HEX.test(value) || value === 'none' || value.includes('(') || /^[\d.]/.test(value)) {
      return value;
    }
    return JSON.stringify(value);
  }
  if (typeof value === 'number') {
    const key = path.at(-1) ?? '';
    if (path.includes('duration') || key.endsWith('Ms')) {
      return `${String(value)}ms`;
    }
    if (
      key === 'desktopLineHeight' ||
      key === 'androidDp' ||
      path.includes('easing') ||
      key === 'weight'
    ) {
      return String(value);
    }
    return `${String(value)}px`;
  }
  if (path.includes('easing')) {
    return `cubic-bezier(${value.map((item) => String(item)).join(', ')})`;
  }
  return value.map((item) => String(item)).join(', ');
}

function walkLeaves(
  value: unknown,
  path: readonly string[],
  visit: (path: readonly string[], leaf: string | number | boolean | readonly number[]) => void,
): void {
  if (typeof value === 'string' || typeof value === 'number' || typeof value === 'boolean') {
    visit(path, value);
    return;
  }
  if (isNumberArray(value)) {
    visit(path, value);
    return;
  }
  if (value === null || typeof value !== 'object') {
    throw new Error(`unsupported token at ${path.join('.')}`);
  }
  for (const [key, child] of Object.entries(value)) {
    walkLeaves(child, [...path, key], visit);
  }
}

function emitTypeScript(tokens: TokensDocument): string {
  return `${GENERATED_HEADER}\n\nexport const tokens = ${emitTsValue(tokens, 0, 'tokens')} as const;\n\nexport type Tokens = typeof tokens;\n`;
}

function emitCss(tokens: TokensDocument): string {
  const shared: string[] = [];
  const light: string[] = [];
  const dark: string[] = [];
  walkLeaves(tokens, [], (path, leaf) => {
    if (path[0] === 'color' && (path[1] === 'light' || path[1] === 'dark')) {
      const rest = path.slice(2);
      const line = `  ${cssName(['color', ...rest])}: ${cssLeaf(rest, leaf)};`;
      if (path[1] === 'light') {
        light.push(line);
      } else {
        dark.push(line);
      }
      return;
    }
    if (path[0] === 'elevation' && (path.at(-1) === 'cssLight' || path.at(-1) === 'cssDark')) {
      const role = path[1];
      if (role === undefined) {
        return;
      }
      const line = `  ${cssName(['elevation', role])}: ${cssLeaf(path, leaf)};`;
      if (path.at(-1) === 'cssLight') {
        light.push(line);
      } else {
        dark.push(line);
      }
      return;
    }
    shared.push(`  ${cssName(path)}: ${cssLeaf(path, leaf)};`);
  });
  return [
    '/* Generated by @jot/tokens. Do not edit. */',
    '',
    ':root {',
    ...shared,
    ...light,
    '}',
    '',
    "[data-theme='light'] {",
    ...light,
    '}',
    '',
    "[data-theme='dark'] {",
    ...dark,
    '}',
    '',
    '@media (prefers-color-scheme: dark) {',
    "  :root:not([data-theme='light']) {",
    ...dark.map((line) => `  ${line}`),
    '  }',
    '}',
    '',
  ].join('\n');
}

function swiftLeaf(value: string | number | boolean | readonly number[]): string {
  if (typeof value === 'boolean') {
    return value ? 'true' : 'false';
  }
  if (typeof value === 'string') {
    return JSON.stringify(value);
  }
  if (typeof value === 'number') {
    return Object.is(value, -0) ? '0' : String(value);
  }
  return `[${value.map((item) => String(item)).join(', ')}]`;
}

function swiftType(value: string | number | boolean | readonly number[]): string {
  if (typeof value === 'boolean') {
    return 'Bool';
  }
  if (typeof value === 'string') {
    return 'String';
  }
  if (typeof value === 'number') {
    return 'Double';
  }
  return '[Double]';
}

function emitSwiftBlock(value: unknown, indent: number, path: string): string {
  const pad = '    '.repeat(indent);
  if (
    typeof value === 'string' ||
    typeof value === 'number' ||
    typeof value === 'boolean' ||
    isNumberArray(value)
  ) {
    throw new Error(`expected object at ${path}`);
  }
  if (value === null || typeof value !== 'object' || Array.isArray(value)) {
    throw new Error(`expected object at ${path}`);
  }
  const entries = Object.entries(value);
  const lines: string[] = [];
  for (const [key, child] of entries) {
    if (
      typeof child === 'string' ||
      typeof child === 'number' ||
      typeof child === 'boolean' ||
      isNumberArray(child)
    ) {
      lines.push(
        `${pad}public static let ${swiftIdent(key)}: ${swiftType(child)} = ${swiftLeaf(child)}`,
      );
      continue;
    }
    const nested = emitSwiftBlock(child, indent + 1, `${path}.${key}`);
    lines.push(`${pad}public enum ${pascalCase(key)} {`);
    lines.push(nested);
    lines.push(`${pad}}`);
  }
  return lines.join('\n');
}

function emitSwift(tokens: TokensDocument): string {
  return [
    GENERATED_HEADER,
    '',
    'public enum JotTokens {',
    emitSwiftBlock(tokens, 1, 'tokens'),
    '}',
    '',
  ].join('\n');
}

function kotlinLeaf(value: string | number | boolean | readonly number[]): string {
  if (typeof value === 'boolean') {
    return value ? 'true' : 'false';
  }
  if (typeof value === 'string') {
    if (HEX.test(value)) {
      return `0xFF${value.slice(1).toUpperCase()}.toInt()`;
    }
    return JSON.stringify(value);
  }
  if (typeof value === 'number') {
    if (Number.isInteger(value)) {
      return String(value);
    }
    return Object.is(value, -0) ? '0.0' : String(value);
  }
  return `doubleArrayOf(${value.map((item) => (Number.isInteger(item) ? `${String(item)}.0` : String(item))).join(', ')})`;
}

function emitKotlinBlock(value: unknown, indent: number, path: string): string {
  const pad = '    '.repeat(indent);
  if (value === null || typeof value !== 'object' || Array.isArray(value)) {
    throw new Error(`expected object at ${path}`);
  }
  const lines: string[] = [];
  for (const [key, child] of Object.entries(value)) {
    if (
      typeof child === 'string' ||
      typeof child === 'number' ||
      typeof child === 'boolean' ||
      isNumberArray(child)
    ) {
      const rendered = kotlinLeaf(child);
      const modifier = rendered.startsWith('doubleArrayOf') ? 'val' : 'const val';
      lines.push(`${pad}${modifier} ${kotlinIdent(key)} = ${rendered}`);
      continue;
    }
    const nested = emitKotlinBlock(child, indent + 1, `${path}.${key}`);
    lines.push(`${pad}object ${pascalCase(key)} {`);
    lines.push(nested);
    lines.push(`${pad}}`);
  }
  return lines.join('\n');
}

function emitKotlin(tokens: TokensDocument): string {
  return [
    GENERATED_HEADER,
    '',
    'package com.jot.tokens',
    '',
    'object Tokens {',
    emitKotlinBlock(tokens, 1, 'tokens'),
    '}',
    '',
  ].join('\n');
}

export function generateFiles(tokens: TokensDocument): GeneratedFiles {
  return {
    'tokens.ts': emitTypeScript(tokens),
    'tokens.css': emitCss(tokens),
    'tokens.swift': emitSwift(tokens),
    'Tokens.kt': emitKotlin(tokens),
  };
}

export function generateFromJsonText(jsonText: string): GeneratedFiles {
  return generateFiles(parseTokens(jsonText));
}

export function writeGenerated(directory: string, files: GeneratedFiles): void {
  mkdirSync(directory, { recursive: true });
  for (const name of GENERATED_FILES) {
    writeFileSync(join(directory, name), files[name], 'utf8');
  }
}

export function packageRootFromModuleUrl(moduleUrl: string): string {
  return join(dirname(fileURLToPath(moduleUrl)), '..');
}

function isCli(moduleUrl: string): boolean {
  const entry = process.argv[1];
  if (entry === undefined) {
    return false;
  }
  return moduleUrl === pathToFileURL(resolve(entry)).href;
}

export function runGenerateCli(moduleUrl: string = import.meta.url): void {
  const root = packageRootFromModuleUrl(moduleUrl);
  const jsonText = readFileSync(join(root, 'src', 'tokens.json'), 'utf8');
  writeGenerated(join(root, 'generated'), generateFromJsonText(jsonText));
}

if (isCli(import.meta.url)) {
  runGenerateCli();
}

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { parseTokens } from './parse.js';
import type { TokensDocument } from './types.js';

export const GENERATED_HEADER = '// Generated by @jot/tokens. Do not edit.';

export const GENERATED_FILES = ['tokens.ts', 'tokens.css', 'tokens.swift', 'Tokens.kt'] as const;

export type GeneratedFileName = (typeof GENERATED_FILES)[number];

export type GeneratedFiles = Record<GeneratedFileName, string>;

const HEX = /^#[0-9a-f]{6}$/;

function isIdent(key: string): boolean {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key);
}

function kebabSegment(segment: string): string {
  return segment
    .replaceAll(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replaceAll('_', '-')
    .toLowerCase();
}

function cssName(path: readonly string[]): string {
  return `--jot-${path.map(kebabSegment).join('-')}`;
}

function pascalCase(key: string): string {
  if (key === 'type') {
    return 'Typography';
  }
  const parts = key
    .replaceAll(/([a-z0-9])([A-Z])/g, '$1 $2')
    .replaceAll(/[^A-Za-z0-9]+/g, ' ')
    .split(' ')
    .filter((part) => part.length > 0)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1));
  const body = parts.join('');
  if (body.length === 0) {
    return 'Token';
  }
  if (/^[0-9]/.test(body)) {
    return `N${body}`;
  }
  return body;
}


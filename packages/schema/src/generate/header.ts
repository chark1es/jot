export function kotlinEnumName(name: string): string {
  return name.replace(/([a-z\d])([A-Z])/g, "$1_$2").toUpperCase();
}

export function swiftTypeName(name: string): string {
  return name.charAt(0).toUpperCase() + name.slice(1);
}
